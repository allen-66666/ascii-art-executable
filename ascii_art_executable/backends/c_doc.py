"""c_doc —— 真正解释代码作用的英文注释（不是装饰性图案）。

用户要求"辅助生成图案的注释是真正有用的内容"。本模块为每条真实语句生成一句
英文说明；图案块本身也用英文标注其用途。规则简单、确定性，覆盖大一 C 程序里
常见的语句类型；未命中时给一句通用说明。
"""

from __future__ import annotations


def explain(text: str) -> str:
    """Return a short English sentence explaining what the statement does."""
    t = text.strip()
    low = t.lower()

    if t.startswith("#include"):
        header = t.split()[-1].strip("<>\"")
        return f"Include the {header} header to make its declarations available."
    if t.startswith("#define"):
        return "Define a preprocessor macro used later in the file."
    if "printf" in low or "puts" in low or "fputs" in low:
        return "Write text to standard output."
    if "scanf" in low or "fgets" in low:
        return "Read input from standard input."
    if low.startswith("return"):
        return "Return control to the caller; 0 signals successful execution."
    if low.startswith(("for ", "for(")):
        return "Repeat the loop body over a range of values."
    if low.startswith(("while ", "while(")):
        return "Repeat the body while the condition remains true."
    if low.startswith(("if ", "if(")):
        return "Execute the next statement only when the condition is true."
    if low.startswith(("int ", "float ", "double ", "char ", "long ")):
        return "Declare a variable and optionally give it an initial value."
    if "=" in t and t.endswith(";"):
        return "Assign a value that the following logic uses."
    if t in ("{", "}", "};"):
        return "Mark the boundary of a code block."
    if "main" in low:
        return "Define the program entry point where execution begins."
    return "Perform one step of the program's logic."


def short_explain(text: str) -> str:
    """Concise phrase for tight token-shaped layouts (fits short arc runs)."""
    t = text.strip()
    low = t.lower()

    if t.startswith("#include"):
        return "Include header"
    if t.startswith("#define"):
        return "Define macro"
    if "scanf" in low or "fgets" in low:
        return "Read input"
    if "printf" in low or "puts" in low or "fputs" in low:
        return "Print output"
    if low.startswith("return"):
        return "Return success"
    if low.startswith(("for ", "for(")):
        return "Loop over i"
    if low.startswith(("while ", "while(")):
        return "While loop"
    if low.startswith(("if ", "if(")):
        return "If condition"
    if low.startswith(("int ", "float ", "double ", "char ", "long ")):
        return "Declare variable"
    if t in ("{", "}", "};"):
        return "Block boundary"
    if "+=" in t or "-=" in t:
        return "Update value"
    if "=" in t and t.endswith(";"):
        return "Assign value"
    if "main" in low:
        return "Entry point"
    return "One logic step"


def canvas_label() -> str:
    """English label placed inside the pattern block, above the first pattern row."""
    return (" * ASCII art canvas: decorative pattern. The executable statements "
            "are placed after this block.")


def file_header(program_name: str, mode: str) -> list[str]:
    """Top-of-file English documentation block."""
    return [
        "/*",
        f" * {program_name}",
        " * Generated by the ASCII Art Executable (C backend).",
        f" * Fill mode: {mode}. The program compiles, runs, and keeps its original behavior.",
        " */",
    ]
